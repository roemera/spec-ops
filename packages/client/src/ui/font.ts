/** Draw text with the bitmap font. Returns the width in pixels. */
export function drawText(
  ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string,
  scale = 1, align: 'left' | 'center' | 'right' = 'left',
) {
  text = text.toUpperCase();
  const w = text.length * 4 * scale - scale;
  let cx = align === 'center' ? Math.round(x - w / 2) : align === 'right' ? x - w : x;
  ctx.fillStyle = color;
  for (const ch of text) {
    const g = G[ch] ?? G['?'];
    for (let i = 0; i < 15; i++) if (g[i] === '#') ctx.fillRect(cx + (i % 3) * scale, y + Math.floor(i / 3) * scale, scale, scale);
    cx += 4 * scale;
  }
  return w;
}
